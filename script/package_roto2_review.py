"""Build a reproducible, source-hashed research handoff from saved local evidence.

Copies experiment evidence verbatim. Does not include installed dependencies,
unrelated experiments, credentials, or invent missing PPO transition records.
Run with the project Python (TensorBoard installed) from the repository root.
"""
from __future__ import annotations

import argparse
import csv
from datetime import datetime, timezone
import gzip
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tarfile

ROOT = Path(__file__).resolve().parents[1]
REVIEW = ROOT / "research/roto2_review/2026-10-20"
LARGE = ROOT / "simulation/.runtime/review_upload"
ARCHIVE_NAME = "roto2-20261020-models-and-assets.tar.gz"
SKIP_DIRS = {"__pycache__", "uv-cache", "wheels"}
CHECKPOINT_SUFFIXES = {".pt", ".pth", ".ckpt"}
SECRET_PATTERNS = {
    "github_token": re.compile(r"\b(?:gh[pousr]_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{35,})"),
    "hf_token": re.compile(r"\bhf_[A-Za-z0-9]{30,}"),
    "private_key": re.compile(r"-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----"),
    "url_password": re.compile(r"https?://[^/\s:@]+:[^/\s@]{5,}@"),
    "bearer_literal": re.compile(r"Authorization:\s*Bearer\s+[A-Za-z0-9._-]{20,}", re.I),
}


def sha(path):
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def write_json(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")


def write_csv(path, rows, fields):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def read_json(path):
    try:
        return json.loads(path.read_text())
    except (UnicodeDecodeError, ValueError, OSError):
        return None


def selected_files():
    roots = [
        ROOT / "logs/roto2_pressure_fruit",
        ROOT / "simulation/.runtime/setup",
        ROOT / "artifacts/simulation",
        ROOT / "botSDK/urdf/02_project_derived/isaac_assets/single_l20_right_rotation",
    ]
    files, exclusions = [], []
    for root in roots:
        for parent, dirs, names in os.walk(root, followlinks=False):
            for name in list(dirs):
                if name in SKIP_DIRS or (root.name == "simulation" and name == "tomato_pick_clean_v5"):
                    exclusions.append({"path": str((Path(parent) / name).relative_to(ROOT)),
                                       "reason": "dependency cache, bytecode, or unrelated tomato-pick experiment"})
                    dirs.remove(name)
            for name in names:
                f = Path(parent) / name
                if f.is_symlink() or f.suffix in {".pyc", ".pyo"}:
                    exclusions.append({"path": str(f.relative_to(ROOT)), "reason": "symlink or generated bytecode"})
                else:
                    files.append(f)
    wrapper = ROOT / "simulation/.runtime/run_roto2.sh"
    if wrapper.exists():
        files.append(wrapper)
    return sorted(set(files)), exclusions


def security_check(files):
    issues = []
    for f in files:
        if f.suffix in CHECKPOINT_SUFFIXES | {".mp4", ".npz", ".png", ".jpg", ".usd", ".usdc"}:
            continue
        try:
            text = f.read_text()
        except UnicodeDecodeError:
            continue
        for kind, regex in SECRET_PATTERNS.items():
            if regex.search(text):
                issues.append({"file": str(f.relative_to(ROOT)), "kind": kind})
    if issues:
        # Deliberately never print matched secret values.
        raise RuntimeError("Potential literal credentials in selected files: " + json.dumps(issues))
    return {"selected_files_scanned": len(files), "credential_pattern_matches": 0,
            "note": "Heuristic scan, not a guarantee; dependency caches and unrelated directories excluded."}


def make_registries(files):
    run_rows = []
    for folder in sorted((ROOT / "logs/roto2_pressure_fruit").glob("*/*")):
        if not folder.is_dir():
            continue
        cfg = read_json(folder / "run_config.json") or {}
        result = read_json(folder / "training_result.json") or {}
        progress = read_json(folder / "progress.json") or {}
        if not any((cfg, result, progress, list(folder.glob("events.out*")))):
            continue
        run_rows.append({
            "run": str(folder.relative_to(ROOT)),
            "status": "completed_training" if result.get("training_completed") else
                      "partial_progress_saved" if progress else "config_or_events_only",
            "seed": cfg.get("seed", result.get("seed")),
            "reward_version": cfg.get("reward_version", "legacy_unversioned"),
            "reward_stage": cfg.get("reward_stage", "not_recorded"),
            "hand_posture": cfg.get("hand_posture", "not_recorded"),
            "domain_profile": cfg.get("domain_profile", "not_recorded"),
            "goal_direction": cfg.get("goal_direction", "not_recorded"),
            "num_envs": cfg.get("num_envs"), "num_eval_envs": cfg.get("num_eval_envs"),
            "additional_training_transitions": result.get("training_transitions"),
            "saved_progress_transitions": progress.get("training_transitions"),
            "cumulative_lineage_transitions": result.get("cumulative_training_transitions"),
            "ppo_updates": result.get("ppo_updates"), "elapsed_seconds": result.get("elapsed_seconds"),
            "finite_parameters": result.get("finite_parameters"),
            "resumed_from": cfg.get("resumed_from", result.get("resumed_from")),
            "final_checkpoint": result.get("final_checkpoint"),
            "config_path": str((folder / "run_config.json").relative_to(ROOT)) if cfg else None,
            "result_path": str((folder / "training_result.json").relative_to(ROOT)) if result else None,
            "progress_path": str((folder / "progress.json").relative_to(ROOT)) if progress else None,
            "source_snapshot_present": (folder / "source_snapshot").is_dir(),
            "tensorboard_event_files": len(list(folder.glob("events.out*"))),
            "checkpoint_files": len(list((folder / "checkpoints").glob("*.pt"))),
        })
    evaluations = []
    episodes = []
    for f in files:
        if f.suffix != ".json":
            continue
        d = read_json(f)
        if not isinstance(d, dict) or not isinstance(d.get("episodes"), int) or "success_fraction" not in d:
            continue
        validity = "pose_based_stage_specific" if "rotation_source" in d else "legacy_or_unverified_rotation_metric"
        if "rejected_wrong_quat" in str(f):
            validity = "rejected_initialization"
        row = {
            "source": str(f.relative_to(ROOT)), "validity": validity,
            "checkpoint": d.get("checkpoint"), "episodes": d["episodes"],
            "reward_version": d.get("reward_version", "not_recorded"),
            "stage": d.get("evaluation_reward_stage", "not_recorded"),
            "posture": d.get("hand_posture", "not_recorded"), "profile": d.get("domain_profile", "not_recorded"),
            "direction": d.get("goal_direction", "not_recorded"),
            "success_fraction": d["success_fraction"], "failure_fraction": d.get("failure_fraction"),
            "mean_directed_rotations": d.get("mean_directed_rotations"),
            "mean_secure_support_fraction": d.get("mean_secure_support_fraction"),
            "mean_after_settling_directed_turns": d.get("mean_after_settling_directed_turns"),
            "mean_after_10s_directed_turns": d.get("mean_after_10s_directed_turns"),
            "mean_peak_pressure_proxy_pa": d.get("mean_peak_pressure_proxy_pa"),
            "mean_jacobian_acceptance_fraction": d.get("mean_jacobian_acceptance_fraction"),
            "success_definition": d.get("success_definition"),
            "pose_metric_max_error_turns": d.get("pose_metric_max_error_turns"),
        }
        evaluations.append(row)
        for item in d.get("per_episode", []):
            episodes.append({"source": row["source"], "validity": validity, **item})
    write_json(REVIEW / "tables/runs.json", run_rows)
    write_csv(REVIEW / "tables/runs.csv", run_rows, list(run_rows[0]))
    write_json(REVIEW / "tables/evaluations.json", evaluations)
    write_csv(REVIEW / "tables/evaluations.csv", evaluations, list(evaluations[0]))
    write_json(REVIEW / "tables/episodes.json", episodes)
    write_csv(REVIEW / "tables/episodes.csv", episodes, sorted({k for r in episodes for k in r}))
    from tensorboard.backend.event_processing.event_accumulator import EventAccumulator
    scalar_rows = []
    tb_errors = []
    for row in run_rows:
        if not row["tensorboard_event_files"]:
            continue
        try:
            event = EventAccumulator(str(ROOT / row["run"]), size_guidance={"scalars": 0}).Reload()
            for tag in event.Tags()["scalars"]:
                for value in event.Scalars(tag):
                    scalar_rows.append(dict(run=row["run"], tag=tag, step=value.step,
                                            wall_time=value.wall_time, value=value.value))
        except Exception as exc:
            tb_errors.append({"run": row["run"], "error": str(exc)})
    write_csv(REVIEW / "tables/tensorboard_scalars.csv", scalar_rows,
              ["run", "tag", "step", "wall_time", "value"])
    write_json(REVIEW / "tables/tensorboard_export_status.json",
               {"scalar_rows": len(scalar_rows), "errors": tb_errors})
    if tb_errors:
        raise RuntimeError("TensorBoard exports failed; see status")
    return {"run_directories": len(run_rows),
            "completed_training_runs": sum(r["status"] == "completed_training" for r in run_rows),
            "partial_progress_runs": sum(r["status"] == "partial_progress_saved" for r in run_rows),
            "completed_additional_transitions_sum": sum(r["additional_training_transitions"] or 0 for r in run_rows),
            "completed_training_seconds_sum": sum(r["elapsed_seconds"] or 0 for r in run_rows),
            "evaluation_documents": len(evaluations), "per_episode_rows": len(episodes),
            "tensorboard_scalar_rows": len(scalar_rows),
            "warning": "Transition sum covers completed runs only, including benchmarks and rejected experiments; do not sum cumulative lineage counts. Evaluation docs include repeated checkpoints and invalid historical metrics."}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--skip-archive", action="store_true")
    args = parser.parse_args()
    REVIEW.mkdir(parents=True, exist_ok=True)
    LARGE.mkdir(parents=True, exist_ok=True)
    files, exclusions = selected_files()
    scan = security_check(files)
    manifest = []
    archived = []
    for f in files:
        relative = f.relative_to(ROOT)
        large = f.suffix in CHECKPOINT_SUFFIXES or str(relative).startswith("botSDK/")
        destination = None if large else Path("evidence") / relative
        if large:
            archived.append(f)
        else:
            target = REVIEW / destination
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, target)
        manifest.append({
            "source_path": str(relative), "bytes": f.stat().st_size, "sha256": sha(f),
            "storage": "github_release_archive" if large else "git_branch",
            "review_path": str(destination) if destination else None,
            "archive": ARCHIVE_NAME if large else None,
            "archive_member": str(relative) if large else None,
        })
    write_json(REVIEW / "manifest.json", manifest)
    write_csv(REVIEW / "manifest.csv", manifest, list(manifest[0]))
    write_json(REVIEW / "excluded.json", exclusions)
    write_json(REVIEW / "security_scan.json", scan)
    summary = make_registries(files)
    summary.update({
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "base_commit": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(),
        "branch": subprocess.check_output(["git", "branch", "--show-current"], cwd=ROOT, text=True).strip(),
        "original_file_count": len(files), "original_total_bytes": sum(x["bytes"] for x in manifest),
        "branch_evidence_file_count": len(files) - len(archived),
        "branch_evidence_bytes": sum(x["bytes"] for x in manifest if x["storage"] == "git_branch"),
        "archived_file_count": len(archived),
        "checkpoint_file_count": sum(f.suffix in CHECKPOINT_SUFFIXES for f in archived),
        "raw_transition_dataset_present": False,
    })
    if not args.skip_archive:
        destination = LARGE / ARCHIVE_NAME
        with destination.open("wb") as out:
            with gzip.GzipFile(fileobj=out, mode="wb", compresslevel=1, mtime=0) as compressed:
                with tarfile.open(fileobj=compressed, mode="w|") as archive:
                    for f in archived:
                        archive.add(f, arcname=str(f.relative_to(ROOT)), recursive=False)
        # Read back all members and verify their decompressed bytes, not only tar listings.
        expected = {x["source_path"]: x for x in manifest if x["storage"] == "github_release_archive"}
        verified = set()
        with tarfile.open(destination, "r:gz") as archive:
            for member in archive:
                if not member.isfile() or member.name not in expected:
                    raise RuntimeError(f"Unexpected archive member {member.name}")
                data = archive.extractfile(member)
                digest = hashlib.sha256()
                for block in iter(lambda: data.read(1024 * 1024), b""):
                    digest.update(block)
                if digest.hexdigest() != expected[member.name]["sha256"]:
                    raise RuntimeError(f"Bad archive bytes: {member.name}")
                verified.add(member.name)
        if verified != set(expected):
            raise RuntimeError("Archive omits manifest entries")
        asset = {"name": ARCHIVE_NAME, "bytes": destination.stat().st_size,
                 "sha256": sha(destination), "verified_members": len(verified)}
        write_json(REVIEW / "release_assets.json", [asset])
        (LARGE / "SHA256SUMS").write_text(f"{asset['sha256']}  {ARCHIVE_NAME}\n")
        summary["archive"] = asset
    write_json(REVIEW / "inventory_summary.json", summary)
    print(json.dumps(summary, ensure_ascii=False, indent=2), flush=True)


if __name__ == "__main__":
    main()
